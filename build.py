#!/usr/bin/env python3
"""Build index.html, the single-file page that GitHub Pages serves.

Inlines src/geometry.js into src/app.html and wraps it in a full HTML document.

    python3 build.py            # write index.html
    python3 build.py --check    # fail if index.html is out of date (used by CI)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARKER = "/*__GEOMETRY__*/"
SPLIT = '<div class="app">'


def build() -> str:
    page = (ROOT / "src" / "app.html").read_text(encoding="utf-8")
    geometry = (ROOT / "src" / "geometry.js").read_text(encoding="utf-8")
    if MARKER not in page or SPLIT not in page:
        sys.exit("src/app.html is missing the geometry marker or the app container")
    page = page.replace(MARKER, geometry.rstrip() + "\n")
    head, body = page.split(SPLIT, 1)
    return (
        "<!doctype html>\n<!-- Generated by build.py from src/app.html and src/geometry.js. Edit those, not this file. -->\n"
        '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n'
        "<style>body{margin:0}[hidden]{display:none!important}img{max-width:100%}</style>\n"
        + head.strip() + "\n</head>\n<body>\n" + SPLIT + body.rstrip() + "\n</body>\n</html>\n"
    )


def main() -> None:
    out = ROOT / "index.html"
    html = build()
    if "--check" in sys.argv:
        if not out.exists() or out.read_text(encoding="utf-8") != html:
            sys.exit("index.html is out of date. Run: python3 build.py")
        print("index.html is up to date")
        return
    out.write_text(html, encoding="utf-8")
    print(f"wrote {out.name} ({len(html):,} bytes)")


if __name__ == "__main__":
    main()
